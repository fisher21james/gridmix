# PlatformIO pre-build script: turns files the firmware serves or needs into C headers.
#   device-web/setup.html -> include/generated/setup_html.h  (gzipped bytes, served at http://gridmix.local)
#   data/ca_roots.pem     -> include/generated/ca_roots.h    (root certificates for HTTPS)
Import("env")  # noqa: F821  (provided by PlatformIO)
import gzip
from pathlib import Path

root = Path(env.subst("$PROJECT_DIR"))
out_dir = root / "include" / "generated"
out_dir.mkdir(parents=True, exist_ok=True)


def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


html = (root / "device-web" / "setup.html").read_bytes()
gz = gzip.compress(html, compresslevel=9, mtime=0)
rows = [", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
write_if_changed(out_dir / "setup_html.h",
    "// Generated by scripts/embed_assets.py from device-web/setup.html. Do not edit.\n#pragma once\n#include <stddef.h>\n#include <stdint.h>\n"
    f"static const size_t SETUP_HTML_GZ_LEN = {len(gz)};\n"
    "static const uint8_t SETUP_HTML_GZ[] = {\n  " + ",\n  ".join(rows) + "\n};\n")

pem = "\n".join(l for l in (root / "data" / "ca_roots.pem").read_text().splitlines() if not l.startswith("#")) + "\n"
write_if_changed(out_dir / "ca_roots.h",
    "// Generated by scripts/embed_assets.py from data/ca_roots.pem. Do not edit.\n#pragma once\n"
    f'static const char CA_ROOTS_PEM[] = R"pem({pem})pem";\n')

print(f"Embedded setup page ({len(html)} bytes, {len(gz)} gzipped) and root certificates")
