#!/usr/bin/env python3
"""Converts TrueType fonts into LVGL 9 bitmap fonts (4 bits per pixel) for the display.

Run by hand when fonts change; the generated .c files are committed:
    python3 scripts/make_fonts.py --inter path/to/Inter[opsz,wght].ttf --grotesk path/to/SpaceGrotesk[wght].ttf

Inter and Space Grotesk are under the SIL Open Font License (see lib/gridui/fonts/OFL.txt).
"""
import argparse
from pathlib import Path
from PIL import ImageFont

OUT = Path(__file__).resolve().parent.parent / "lib" / "gridui" / "fonts"

ASCII = list(range(0x20, 0x7F))
EXTRA = [0xA2, 0xA3, 0xB0, 0xB7, 0x2013, 0x2026, 0x2039, 0x203A, 0x2212]   # ¢ £ ° · – … ‹ › −
TEXT = ASCII + EXTRA
DIGITS = [ord(c) for c in " %-.0123456789"] + [0x2212]

# name, family, size px, weight, characters
FONTS = [
    ("gm_inter_11", "inter", 11, 600, TEXT),
    ("gm_inter_12", "inter", 12, 500, TEXT),
    ("gm_inter_13", "inter", 13, 600, TEXT),
    ("gm_grotesk_13", "grotesk", 13, 700, TEXT),
    ("gm_grotesk_15", "grotesk", 15, 700, TEXT),
    ("gm_grotesk_17", "grotesk", 17, 700, TEXT),
    ("gm_grotesk_42", "grotesk", 42, 700, DIGITS),
]


def load(path, size, weight, family):
    f = ImageFont.truetype(str(path), size)
    axes = f.get_variation_axes()
    vals = []
    for a in axes:
        name = a["name"].decode() if isinstance(a["name"], bytes) else str(a["name"])
        if name.lower().startswith("weight"):
            vals.append(weight)
        elif name.lower().startswith("optical"):
            vals.append(max(a["minimum"], min(a["maximum"], size)))
        else:
            vals.append(a["default"])
    if vals:
        f.set_variation_by_axes(vals)
    return f


def pack4(pixels):
    out = bytearray()
    for i in range(0, len(pixels), 2):
        hi = pixels[i] >> 4
        lo = (pixels[i + 1] >> 4) if i + 1 < len(pixels) else 0
        out.append((hi << 4) | lo)
    return out


def convert(name, font, chars):
    ascent, descent = font.getmetrics()
    chars = sorted(set(chars))
    bitmap = bytearray()
    glyphs = []
    for cp in chars:
        ch = chr(cp)
        adv = round(font.getlength(ch) * 16)
        mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        px = [mask.getpixel((x, y)) for y in range(h) for x in range(w)] if w and h else []
        # trim empty rows/columns so boxes are tight
        if px and max(px) == 0:
            w = h = 0
            px = []
        if w and h:
            rows = [px[r * w:(r + 1) * w] for r in range(h)]
            while rows and max(rows[0]) < 16:
                rows.pop(0); oy += 1
            while rows and max(rows[-1]) < 16:
                rows.pop()
            cols = list(zip(*rows)) if rows else []
            left = 0
            while cols and max(cols[0]) < 16:
                cols.pop(0); left += 1
            while cols and max(cols[-1]) < 16:
                cols.pop()
            if not cols:
                w = h = 0; px = []
            else:
                ox += left
                h = len(cols[0]); w = len(cols)
                px = [cols[x][y] for y in range(h) for x in range(w)]
        idx = len(bitmap)
        if w and h:
            bitmap += pack4(px)
        ofs_y = -(oy + h) if h else 0
        glyphs.append(dict(cp=cp, idx=idx, adv=adv, w=w, h=h, ox=ox, oy=ofs_y))

    # cmaps: one dense ASCII range if present, then a sparse list for the rest
    cmaps = []
    gid = 1
    ascii_part = [g for g in glyphs if 0x20 <= g["cp"] < 0x7F]
    rest = [g for g in glyphs if not (0x20 <= g["cp"] < 0x7F)]
    ordered = []
    if ascii_part and [g["cp"] for g in ascii_part] == list(range(ascii_part[0]["cp"], ascii_part[-1]["cp"] + 1)):
        cmaps.append(("range", ascii_part[0]["cp"], len(ascii_part), gid, None))
        gid += len(ascii_part)
        ordered += ascii_part
    else:
        rest = glyphs
    if rest:
        start = rest[0]["cp"]
        cmaps.append(("sparse", start, rest[-1]["cp"] - start + 1, gid, [g["cp"] - start for g in rest]))
        ordered += rest

    lines = [f"// Generated by scripts/make_fonts.py. Do not edit.",
             f"// {len(ordered)} glyphs, 4 bpp.",
             '#include "lvgl.h"', "",
             "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {"]
    for i in range(0, len(bitmap), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    if not bitmap:
        lines.append("    0x00,")
    lines += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {",
              "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"]
    for g in ordered:
        lines.append(f"    {{.bitmap_index = {g['idx']}, .adv_w = {g['adv']}, .box_w = {g['w']}, .box_h = {g['h']}, "
                     f".ofs_x = {g['ox']}, .ofs_y = {g['oy']}}}, /* U+{g['cp']:04X} */")
    lines += ["};", ""]
    cm_lines = []
    for n, (kind, start, length, gstart, lst) in enumerate(cmaps):
        if kind == "sparse":
            lines.append(f"static const uint16_t unicode_list_{n}[] = {{" + ", ".join(f"0x{v:x}" for v in lst) + "};")
            cm_lines.append(f"    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {gstart}, "
                            f".unicode_list = unicode_list_{n}, .glyph_id_ofs_list = NULL, .list_length = {len(lst)}, "
                            f".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},")
        else:
            cm_lines.append(f"    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {gstart}, "
                            f".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                            f".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},")
    lines += ["static const lv_font_fmt_txt_cmap_t cmaps[] = {"] + cm_lines + ["};", ""]
    cap = font.getbbox("H", anchor="ls")
    xh = font.getbbox("x", anchor="ls")
    lines += ["static const lv_font_fmt_txt_dsc_t font_dsc = {",
              "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,",
              f"    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = {len(cmaps)}, .bpp = 4, .kern_classes = 0, .bitmap_format = 0,",
              "};", "",
              f"const lv_font_t {name} = {{",
              "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
              "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
              f"    .line_height = {ascent + descent},",
              f"    .base_line = {descent},",
              "#if LV_VERSION_CHECK(9, 6, 0) || LVGL_VERSION_MAJOR >= 10",
              f"    .cap_height = {-cap[1]},",
              f"    .x_height = {-xh[1]},",
              "#endif",
              "    .subpx = LV_FONT_SUBPX_NONE,",
              "    .underline_position = -1,",
              "    .underline_thickness = 1,",
              "#if LV_VERSION_CHECK(9, 3, 0)",
              "    .static_bitmap = 1,",
              "#endif",
              "    .dsc = &font_dsc,",
              "    .fallback = NULL,",
              "    .user_data = NULL,",
              "};", ""]
    (OUT / f"{name}.c").write_text("\n".join(lines))
    return len(bitmap)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inter", required=True)
    ap.add_argument("--grotesk", required=True)
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    paths = {"inter": args.inter, "grotesk": args.grotesk}
    header = ["// Generated by scripts/make_fonts.py. Do not edit.", "#pragma once", '#include "lvgl.h"', "",
              "#ifdef __cplusplus", 'extern "C" {', "#endif"]
    total = 0
    for name, fam, size, weight, chars in FONTS:
        n = convert(name, load(paths[fam], size, weight, fam), chars)
        total += n
        header.append(f"extern const lv_font_t {name};")
        print(f"{name}: {n} bytes")
    header += ["#ifdef __cplusplus", "}", "#endif", ""]
    (OUT / "gm_fonts.h").write_text("\n".join(header))
    print(f"total {total} bytes of glyphs")


if __name__ == "__main__":
    main()
